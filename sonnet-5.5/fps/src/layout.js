// マップ「塩精錬所・別棟」の配置。南が大ホール（プレイヤーの開始位置）、北が 3 つの部屋。
// 箱は { x0, z0, x1, z1, h, kind, variant }。kind: wall | block | pillar | crate
const wall = (x0, z0, x1, z1) => ({ x0, z0, x1, z1, h: 6, kind: 'wall', variant: 0 });
const crate = (cx, cz, w, d, h, variant) => ({
  x0: cx - w / 2, z0: cz - d / 2, x1: cx + w / 2, z1: cz + d / 2, h, kind: 'crate', variant,
});
const pillar = (cx, cz) => ({ x0: cx - 0.6, z0: cz - 0.6, x1: cx + 0.6, z1: cz + 0.6, h: 6, kind: 'pillar', variant: 0 });

